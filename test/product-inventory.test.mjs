import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,readdir} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import {countProductInventory,listIngredientStock,recordPurchaseReceipt,validateProductCount,validatePurchaseReceipt} from '../src/server/ingredient-stock.mjs';
import {listShoppingRequirements,addStockLot,cancelStockLot} from '../src/server/household-planning.mjs';
import {savePlannedMeal,deletePlannedMeal,listPlannedMeals} from '../src/server/planning.mjs';
import {setMealPrepared} from '../src/server/meal-preparation.mjs';

const householdId='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',other='bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
const foodId='cccccccc-cccc-4ccc-8ccc-cccccccccccc',personId='dddddddd-dddd-4ddd-8ddd-dddddddddddd';
const everyday='eeeeeeee-eeee-4eee-8eee-eeeeeeeeeeee',batch='ffffffff-ffff-4fff-8fff-ffffffffffff';
const date='2026-10-19';

test('product stock follows counted inventory, confirmed purchases, meal cooking and batch cooking',async()=>{
  const db=new PGlite();
  try{
    const dir=new URL('../db/migrations/',import.meta.url);
    for(const file of (await readdir(dir)).filter(file=>file.endsWith('.sql')).sort())await db.exec(await readFile(new URL(file,dir),'utf8'));
    const pool={async query(sql,args=[]){const result=await db.query(sql,args);return {...result,rowCount:result.rows.length||result.affectedRows||0};},async connect(){return {...this,release(){}};}};
    await pool.query("INSERT INTO households(id,name) VALUES($1,'Test'),($2,'Other')",[householdId,other]);
    await pool.query("INSERT INTO foods(id,canonical_name,source) VALUES($1,'Flour','manual')",[foodId]);
    await pool.query("INSERT INTO people(id,household_id,display_name) VALUES($1,$2,'Test')",[personId,householdId]);
    await pool.query("INSERT INTO recipes(id,household_id,name,yield_amount,yield_unit_id) VALUES($1,$2,'Cake',1,'portion')",[everyday,householdId]);
    await pool.query("INSERT INTO recipes(id,household_id,name,yield_amount,yield_unit_id,production_type) VALUES($1,$2,'Batch cake',1,'portion','batch_cooking')",[batch,householdId]);
    await pool.query("INSERT INTO recipe_lines(id,recipe_id,food_id,quantity,unit_id) VALUES(gen_random_uuid(),$1,$2,150,'g'),(gen_random_uuid(),$3,$2,150,'g')",[everyday,foodId,batch]);
    const meal=await savePlannedMeal(pool,null,{householdId,mealDate:date,slot:'lunch',notes:'',attendeeIds:[personId],items:[{recipeId:everyday,role:'main',amounts:[{personId,quantity:1}]}]});
    assert.equal((await listShoppingRequirements(pool,householdId,date,date))[0].neededQuantity,150);
    assert.ok(validateProductCount({householdId,foodId,quantity:0,unitId:'g',version:0}).data);
    assert.equal((await countProductInventory(pool,{householdId,foodId,quantity:50,unitId:'g',version:0})).quantityG,50);
    assert.equal((await countProductInventory(pool,{householdId,foodId,quantity:80,unitId:'g',version:0})).error,'ingredient-stock-changed');
    assert.equal((await listShoppingRequirements(pool,householdId,date,date))[0].neededQuantity,100);
    const receipt={householdId,foodId,quantity:0.1,unitId:'kg',requestId:'11111111-1111-4111-8111-111111111111'};
    assert.ok(validatePurchaseReceipt(receipt).data);
    assert.equal((await recordPurchaseReceipt(pool,receipt)).quantityG,100);
    assert.equal((await recordPurchaseReceipt(pool,receipt)).replayed,true);
    assert.equal((await recordPurchaseReceipt(pool,{...receipt,quantity:0.2})).error,'purchase-request-conflict');
    assert.equal((await listIngredientStock(pool,householdId))[0].quantityG,150);
    assert.deepEqual(await listShoppingRequirements(pool,householdId,date,date),[]);
    assert.equal((await recordPurchaseReceipt(pool,{...receipt,householdId:other,requestId:'22222222-2222-4222-8222-222222222222'})).error,undefined);
    assert.equal((await listIngredientStock(pool,householdId))[0].quantityG,150);
    assert.equal((await setMealPrepared(pool,householdId,meal.id,true)).deductions[0].usedG,150);
    assert.equal((await listIngredientStock(pool,householdId))[0].quantityG,0);
    assert.deepEqual(await listShoppingRequirements(pool,householdId,date,date),[]);
    assert.equal((await setMealPrepared(pool,householdId,meal.id,true)).replayed,true);
    assert.equal((await savePlannedMeal(pool,meal.id,{householdId,mealDate:date,slot:'lunch',notes:'changed',attendeeIds:[personId],items:[{recipeId:everyday,role:'main',amounts:[{personId,quantity:1}]}]})).error,'prepared-meal-locked');
    assert.equal((await deletePlannedMeal(pool,meal.id,householdId)).error,'prepared-meal-locked');
    assert.ok((await listPlannedMeals(pool,householdId,date))[0].preparedAt);
    assert.equal((await setMealPrepared(pool,householdId,meal.id,false)).restored[0].quantityG,150);
    assert.equal((await listIngredientStock(pool,householdId))[0].quantityG,150);
    assert.equal((await setMealPrepared(pool,householdId,meal.id,true)).deductions[0].usedG,150);
    assert.equal((await setMealPrepared(pool,householdId,meal.id,false)).restored[0].quantityG,150);
    const batchMeal=await savePlannedMeal(pool,null,{householdId,mealDate:date,slot:'dinner',notes:'',attendeeIds:[personId],items:[{recipeId:batch,role:'main',amounts:[{personId,quantity:1}]}]});
    assert.equal((await setMealPrepared(pool,householdId,batchMeal.id,true)).error,'prepared-batch-insufficient');
    const lot=await addStockLot(pool,{householdId,recipeId:batch,producedOn:date,quantity:1,storage:'fridge',note:'',requestId:null});
    assert.equal(lot.deductions[0].usedG,150);
    assert.equal((await setMealPrepared(pool,householdId,batchMeal.id,true)).prepared,true);
    assert.equal((await listIngredientStock(pool,householdId))[0].quantityG,0);
    assert.equal((await cancelStockLot(pool,householdId,lot.id)).error,'production-already-used');
    assert.equal((await setMealPrepared(pool,householdId,batchMeal.id,false)).prepared,false);
    assert.equal((await cancelStockLot(pool,householdId,lot.id)).cancelled,true);
    assert.equal((await listIngredientStock(pool,householdId))[0].quantityG,150);
    const egg='99999999-9999-4999-8999-999999999999';
    await pool.query("INSERT INTO foods(id,canonical_name,source,grams_per_millilitre) VALUES($1,'Egg test','manual',0.8)",[egg]);
    await pool.query("INSERT INTO food_unit_conversions(food_id,unit_id,grams_per_unit,source_note) VALUES($1,'piece',50,'Synthetic')",[egg]);
    assert.equal((await countProductInventory(pool,{householdId,foodId:egg,quantity:2,unitId:'piece',version:0})).quantityG,100);
    assert.equal((await recordPurchaseReceipt(pool,{householdId,foodId:egg,quantity:125,unitId:'ml',requestId:'33333333-3333-4333-8333-333333333333'})).quantityG,100);
    assert.equal((await countProductInventory(pool,{householdId,foodId:egg,quantity:0,unitId:'piece',version:2})).quantityG,0);
    const unknown='88888888-8888-4888-8888-888888888888';
    await pool.query("INSERT INTO foods(id,canonical_name,source) VALUES($1,'Unknown piece','manual')",[unknown]);
    assert.equal((await recordPurchaseReceipt(pool,{householdId,foodId:unknown,quantity:1,unitId:'piece',requestId:'44444444-4444-4444-8444-444444444444'})).error,'ingredient-conversion-missing');
    assert.equal((await countProductInventory(pool,{householdId,foodId:unknown,quantity:0,unitId:'piece',version:0})).quantityG,0);
  }finally{await db.close();}
});
