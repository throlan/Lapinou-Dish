#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const input = path.join(root, 'data/ciqual/ciqual-2025.json');
const outputArg = process.argv.indexOf('--output');
const output = outputArg >= 0 ? process.argv[outputArg + 1] : null;
if (outputArg >= 0 && !output) throw new Error('Usage: node scripts/seed-ciqual.mjs [--output chemin.sql]');

const data = JSON.parse(await readFile(input, 'utf8'));
if (data.source !== 'Anses Ciqual 2025' || !Array.isArray(data.foods)) throw new Error('Dataset Ciqual invalide');
const idx = Object.fromEntries(data.constituents.map((code, i) => [code, i]));
const nutrientColumns = [
  ['energy_kcal', '328'], ['protein_g', '25000'], ['carbohydrate_g', '31000'],
  ['fat_g', '40000'], ['fibre_g', '34100'],
];
const sql = [];
sql.push('-- Generated by scripts/seed-ciqual.mjs. Do not edit by hand.');
sql.push('BEGIN;');
sql.push(`-- Source: ${data.source}, dataset version ${data.version}; ${data.foods.length} records.`);

for (const [code, name, english, values, confidence] of data.foods) {
  if (!code || !name?.trim()) throw new Error(`Ciqual row has no code/name: ${code}`);
  const foodId = stableUuid(`ciqual-food:${code}`);
  sql.push(`INSERT INTO foods (id, canonical_name, source, source_reference, source_note) VALUES (${q(foodId)}, ${q(name.trim())}, 'ciqual', ${q(code)}, ${q(`${data.source} ${data.version}; confidence=${confidence}`)}) ON CONFLICT (source_reference) WHERE source = 'ciqual' DO UPDATE SET canonical_name = EXCLUDED.canonical_name, source_note = EXCLUDED.source_note, updated_at = now() WHERE foods.manual_override = false;`);
  for (const [nutrientId, constituentCode] of nutrientColumns) {
    const value = values[idx[constituentCode]];
    const number = typeof value === 'number' && Number.isFinite(value) && value >= 0 ? value : null;
    sql.push(`INSERT INTO food_nutrients (food_id, nutrient_id, value_per_100g, source_note) VALUES (${q(foodId)}, ${q(nutrientId)}, ${number === null ? 'NULL' : number}, ${q(`${data.source} ${data.version}`)}) ON CONFLICT (food_id, nutrient_id) DO UPDATE SET value_per_100g = EXCLUDED.value_per_100g, source_note = EXCLUDED.source_note WHERE NOT (SELECT manual_override FROM foods WHERE id = EXCLUDED.food_id);`);
  }
  if (english?.trim() && english.trim() !== name.trim()) addAlias(code, foodId, english.trim());
  addAlias(code, foodId, name.trim());
}
sql.push('COMMIT;');
const contents = `${sql.join('\n')}\n`;
if (output) {
  const destination = path.resolve(output);
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, contents, 'utf8');
}
else process.stdout.write(contents);

function q(value) { return `'${String(value).replaceAll("'", "''")}'`; }
function addAlias(code, foodId, alias) {
  const normalized = normalize(alias);
  if (!normalized) return;
  const aliasId = stableUuid(`ciqual-alias:${code}:${normalized}`);
  sql.push(`INSERT INTO food_aliases (id, food_id, alias, normalized_alias, source) VALUES (${q(aliasId)}, ${q(foodId)}, ${q(alias)}, ${q(normalized)}, 'ciqual') ON CONFLICT (food_id, normalized_alias) DO UPDATE SET alias = EXCLUDED.alias, source = EXCLUDED.source;`);
}
function normalize(value) {
  return value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/œ/g, 'oe').replace(/æ/g, 'ae').replace(/[^a-z0-9]+/g, ' ').trim();
}
function stableUuid(key) {
  const bytes = createHash('sha256').update(key).digest().subarray(0, 16);
  bytes[6] = (bytes[6] & 0x0f) | 0x80; // UUID v8, deterministic application namespace.
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = bytes.toString('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
