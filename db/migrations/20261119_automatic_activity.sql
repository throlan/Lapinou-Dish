CREATE TABLE person_automatic_profiles (
 id uuid PRIMARY KEY,person_id uuid NOT NULL REFERENCES people(id) ON DELETE CASCADE,
 effective_from date NOT NULL,settings jsonb NOT NULL,
 revision_order bigint GENERATED BY DEFAULT AS IDENTITY,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE person_activity_plans (
 id uuid PRIMARY KEY,person_id uuid NOT NULL REFERENCES people(id) ON DELETE CASCADE,
 effective_from date NOT NULL,activity_type text NOT NULL CHECK(activity_type IN('walk_slow','walk','walk_moderate')),
 minutes_per_session integer NOT NULL CHECK(minutes_per_session BETWEEN 1 AND 180),
 sessions_per_week integer NOT NULL CHECK(sessions_per_week BETWEEN 1 AND 7),additional boolean NOT NULL,
 revision_order bigint GENERATED BY DEFAULT AS IDENTITY,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE person_activity_sessions (
 id uuid PRIMARY KEY,person_id uuid NOT NULL REFERENCES people(id) ON DELETE CASCADE,
 performed_on date NOT NULL,activity_type text NOT NULL CHECK(activity_type IN('walk_slow','walk','walk_moderate')),
 duration_minutes integer NOT NULL CHECK(duration_minutes BETWEEN 1 AND 600),additional boolean NOT NULL,
 cancelled_at timestamptz,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE person_automatic_state (
 person_id uuid PRIMARY KEY REFERENCES people(id) ON DELETE CASCADE,
 input_hash text NOT NULL,result jsonb NOT NULL,updated_at timestamptz NOT NULL DEFAULT now()
);
