-- Dated, explicitly confirmed targets. Existing values are preserved, never estimated here.
-- Materialize legacy name defaults once; runtime targets are keyed only by person id.
UPDATE households h SET protein_targets=coalesce((SELECT jsonb_object_agg(p.id::text,
 CASE lower(trim(p.display_name)) WHEN 'bibinette' THEN 90 WHEN 'lapinou' THEN 125 WHEN 'bibou' THEN 85 WHEN 'titus' THEN 50 END)
 FROM people p WHERE p.household_id=h.id AND lower(trim(p.display_name)) IN('bibinette','lapinou','bibou','titus')),'{}'::jsonb)||h.protein_targets;
CREATE TABLE person_nutrition_goals (
 id uuid PRIMARY KEY,person_id uuid NOT NULL REFERENCES people(id) ON DELETE CASCADE,
 effective_from date NOT NULL,daily_energy_kcal integer NOT NULL CHECK(daily_energy_kcal BETWEEN 500 AND 10000),
 daily_protein_g numeric(8,3) CHECK(daily_protein_g BETWEEN 0 AND 500),
 origin text NOT NULL CHECK(origin IN('manual','clinician','estimate')),method text NOT NULL DEFAULT '',
 reference_weight_kg numeric(6,2),revision_order bigint GENERATED BY DEFAULT AS IDENTITY,
 confirmed_at timestamptz NOT NULL DEFAULT now(),created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX person_nutrition_goals_date_idx ON person_nutrition_goals(person_id,effective_from DESC,revision_order DESC);
INSERT INTO person_nutrition_goals(id,person_id,effective_from,daily_energy_kcal,daily_protein_g,origin,method)
 SELECT ph.id,ph.person_id,ph.effective_from,ph.daily_energy_kcal,
 CASE WHEN h.protein_targets ? p.id::text THEN (h.protein_targets->>p.id::text)::numeric
 ELSE CASE lower(trim(p.display_name)) WHEN 'bibinette' THEN 90 WHEN 'lapinou' THEN 125 WHEN 'bibou' THEN 85 WHEN 'titus' THEN 50 END END,
 ph.daily_energy_origin,coalesce(ph.daily_energy_method,'')
 FROM person_profile_history ph JOIN people p ON p.id=ph.person_id JOIN households h ON h.id=p.household_id
 WHERE ph.daily_energy_kcal IS NOT NULL ORDER BY ph.revision_order;
UPDATE person_nutrition_goals goal SET reference_weight_kg=(SELECT weight_kg FROM person_weight_entries weight WHERE weight.person_id=goal.person_id AND measured_on<=goal.effective_from ORDER BY measured_on DESC LIMIT 1);
ALTER TABLE person_nutrition_goals ENABLE ROW LEVEL SECURITY;
CREATE POLICY household_scope ON person_nutrition_goals USING (
 EXISTS(SELECT 1 FROM people p WHERE p.id=person_id AND p.household_id=NULLIF(current_setting('app.household_id',true),'')::uuid)
 AND (current_setting('app.is_manager',true)='true' OR person_id=NULLIF(current_setting('app.person_id',true),'')::uuid)
) WITH CHECK (
 EXISTS(SELECT 1 FROM people p WHERE p.id=person_id AND p.household_id=NULLIF(current_setting('app.household_id',true),'')::uuid)
 AND (current_setting('app.is_manager',true)='true' OR person_id=NULLIF(current_setting('app.person_id',true),'')::uuid)
);
GRANT SELECT,INSERT ON person_nutrition_goals TO lapinou_request;
GRANT USAGE,SELECT ON SEQUENCE person_nutrition_goals_revision_order_seq TO lapinou_request;

CREATE VIEW effective_energy_history WITH (security_invoker=true) AS
 SELECT person_id,effective_from,daily_energy_kcal,revision_order,0 AS priority FROM person_profile_history WHERE daily_energy_kcal IS NOT NULL
 UNION ALL
 SELECT person_id,effective_from,daily_energy_kcal,revision_order,1 AS priority FROM person_nutrition_goals;
GRANT SELECT ON effective_energy_history TO lapinou_request;
