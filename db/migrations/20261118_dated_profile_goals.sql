-- Keep every correction to a dated profile while leaving existing rows intact.
ALTER TABLE person_profile_history DROP CONSTRAINT person_profile_history_person_id_effective_from_key;
ALTER TABLE person_profile_history ADD COLUMN revision_order bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX person_profile_effective_revision_idx ON person_profile_history (person_id, effective_from DESC, revision_order DESC);

CREATE TABLE person_weight_goals (
  id uuid PRIMARY KEY,
  person_id uuid NOT NULL REFERENCES people(id) ON DELETE CASCADE,
  effective_from date NOT NULL,
  comfortable_weight_kg numeric(6,2) NOT NULL CHECK (comfortable_weight_kg > 0 AND comfortable_weight_kg <= 500),
  interim_target_kg numeric(6,2) CHECK (interim_target_kg > 0 AND interim_target_kg <= 500),
  revision_order bigint GENERATED BY DEFAULT AS IDENTITY,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX person_weight_goals_effective_revision_idx ON person_weight_goals (person_id, effective_from DESC, revision_order DESC);
ALTER TABLE person_weight_goals ENABLE ROW LEVEL SECURITY;
CREATE POLICY household_scope ON person_weight_goals USING (
  EXISTS(SELECT 1 FROM people p WHERE p.id=person_id AND p.household_id=NULLIF(current_setting('app.household_id',true),'')::uuid)
  AND (current_setting('app.is_manager',true)='true' OR person_id=NULLIF(current_setting('app.person_id',true),'')::uuid)
) WITH CHECK (
  EXISTS(SELECT 1 FROM people p WHERE p.id=person_id AND p.household_id=NULLIF(current_setting('app.household_id',true),'')::uuid)
  AND (current_setting('app.is_manager',true)='true' OR person_id=NULLIF(current_setting('app.person_id',true),'')::uuid)
);
GRANT SELECT, INSERT ON person_weight_goals TO lapinou_request;
GRANT USAGE, SELECT ON SEQUENCE person_weight_goals_revision_order_seq TO lapinou_request;
